
-- script to create tables for Assignment 2 

CREATE TABLE UNIVERSITY (
    NAME VARCHAR(30),
    UID INTEGER PRIMARY KEY,
    CITY VARCHAR(30),
    STATE VARCHAR(30),
    URL VARCHAR(100)
);

CREATE TABLE DEGREE( 
    name VARCHAR (30),
    TYPE VARCHAR(10),
    DID INTEGER PRIMARY KEY
    
);


CREATE TABLE COUNTRY (
    NAME VARCHAR(30),
    CID INTEGER PRIMARY KEY
    
);

CREATE TABLE AGENTS (
    
    FNAME VARCHAR(30),
    LNAME VARCHAR(30),
    AID INTEGER PRIMARY KEY,
    PHONE VARCHAR (20),
    EMAIL VARCHAR(100),
    COMMISSION DECIMAL,
    RESIDES_IN_CITY VARCHAR(30),
    CID INTEGER,
    UID INTEGER,
    FOREIGN KEY (UID) REFERENCES UNIVERSITY,
    FOREIGN KEY (CID) REFERENCES COUNTRY
);


CREATE TABLE RECRUITS_FROM (
    UID INTEGER,
    CID INTEGER,
    numstudents INTEGER,
    
    PRIMARY KEY (UID, CID)
);

CREATE TABLE DEGREE_OFFERED (
    UID INTEGER,
    DID integer,

    PRIMARY KEY (UID, DID),
    FOREIGN KEY (UID) REFERENCES UNIVERSITY,
    FOREIGN KEY (DID) REFERENCES DEGREE
);

